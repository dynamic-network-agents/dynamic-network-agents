"""闭环控制：epoch 状态机、下发闸门、实测校验。

一次 epoch = 一次冻结快照 + 一次规划 + 一个下发批 + 一次校验：

1. **触发**：只认可行动事件（链路/节点状态变化、业务转为非 running），**忽略
   自己下发产生的 `pathChanged` 事件**；事件成簇先合窗再规划。
2. **规划是纯函数、下发是增量**：拿计划与已装路径做差集，只有「路径失效（修复）」
   或「加权达标数增益 ≥ Δmin」才下发。
3. **批内不重算**：批是一次计划的执行，中途重算等于换计划；批内收到新事件即中止。
4. **批后静置 + 校验**：多 1s 窗投票比较「预测达标」与「实测达标」，失配路径进
   惩罚集（下一轮候选剔除），纠正轮数有上限。
5. **静默期**：收敛后只做低频心跳，且只对**上一轮预测达标**的 flow 检查
   （物理上救不回来的 flow 不参与判据，否则永远不收敛）。

模块：

- `loop.py`：`Orchestrator` 状态机（IDLE → SETTLING → VERIFYING）。
- `dispatch_gate.py`：纯函数闸门，判定本 epoch 哪些 flow 值得下发。
- `verifier.py`：采样投票、惩罚集、有界纠正、心跳判据。

agents 可复用同一套控制逻辑，只替换决策核心，从而保证与 baseline 对比实验的
唯一差异是「谁来做规划决策」。
"""
